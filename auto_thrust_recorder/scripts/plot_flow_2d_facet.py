def _safe_to_numeric(df: pd.DataFrame, cols):
    for c in cols:
        if c in df.columns:
            df[c] = pd.to_numeric(df[c], errors="coerce")
    return df


def load_and_filter(input_path: Path, target_thrust: float | None) -> pd.DataFrame:
    """結合CSVを読み込み、target_thrust でフィルタし、keyword 平均を行った DataFrame を返す。"""
    try:
        df = pd.read_csv(input_path)
    except Exception as e:
        raise RuntimeError(f"CSV 読み込みに失敗しました: {e}")

    required_cols = [
        "flow_distance",
        "flow_height",
        "flow_direction",
        "front_in",
        "front_out",
        "rear_in",
        "rear_out",
        "target_thrust",
    ]
    missing = [c for c in required_cols if c not in df.columns]
    if missing:
        raise ValueError(f"必須列が不足しています: {', '.join(missing)}")

    # 数値化（必要列のみ）
    num_cols = [
        "flow_distance",
        "flow_height",
        "flow_direction",
        "front_in",
        "front_out",
        "rear_in",
        "rear_out",
        "target_thrust",
        "distance",
        "fold_angle",
        "height",
        "prop_spacing",
        "tilt_angle",
        "wall_spacing",
    ]
    df = _safe_to_numeric(df, num_cols)

    # target_thrust でフィルタ（指定なしなら最大値のみ）
    if df["target_thrust"].notna().sum() == 0:
        raise ValueError("target_thrust 列に有効な値がありません。")
    if target_thrust is None:
        th = df["target_thrust"].max()
        df = df[df["target_thrust"] == th].copy()
        print(f"target_thrust 未指定のため、最大値 {th} のみを使用します。")
    else:
        df = df[df["target_thrust"] == target_thrust].copy()
        if df.empty:
            raise ValueError(f"指定された target_thrust={target_thrust} に一致する行がありません。")

    # keyword の平均化：keyword 以外のパラメータでグループ化し、数値列は平均
    keyword_col = "keyword"
    if keyword_col in df.columns:
        # 数値列と非数値列を分ける
        numeric_cols = df.select_dtypes(include=[np.number]).columns.tolist()
        group_cols = [c for c in df.columns if c not in numeric_cols and c != keyword_col]
        if not group_cols:
            # 念のためのフォールバック：keyword だけ外して平均
            group_cols = [c for c in df.columns if c != keyword_col]
        df = (
            df.groupby(group_cols, dropna=False)
            .mean(numeric_only=True)
            .reset_index()
        )
        print("keyword 列を除いて数値列を平均化しました。")

    return df


def reconstruct_components(df: pd.DataFrame, single_angle_mode: str = "nan") -> pd.DataFrame:
    """flow_direction[deg] と各センサ値から |u_x|,|u_y|,|u| を再構成する。

    - 速度ベクトル u を大きさ U>=0, 角度 phi (向きなし、[0,pi) に制限) とみなし、
      各測定を m_i ≈ U * |cos(theta_i - phi)| として最小二乗フィットする。
    - theta_i は flow_direction[deg]、m_i は各センサ(front_in など)の値。
    - 各 (distance, flow_distance, flow_height, ..., target_thrust, センサ) ごとに
      (U, phi) を推定し、そこから |u_x|, |u_y| を計算する。
    """
    sensors = ["front_in", "front_out", "rear_in", "rear_out"]

    dfc = df.copy()

    # インデックスに使う基本パラメータ列
    base_index_cols_all = [
        "distance",
        "flow_distance",
        "flow_height",
        "fold_angle",
        "height",
        "prop_spacing",
        "tilt_angle",
        "wall_spacing",
        "target_thrust",
    ]
    base_index_cols = [c for c in base_index_cols_all if c in dfc.columns]
    if "flow_distance" not in base_index_cols or "flow_height" not in base_index_cols:
        raise ValueError("flow_distance および flow_height 列が必要です。")

    # phi 探索グリッド（0〜pi、1deg 刻み相当）
    phi_grid = np.linspace(0.0, np.pi, 180, endpoint=False)

    all_pivot = None

    for sensor in sensors:
        if sensor not in dfc.columns:
            continue

        cols = base_index_cols + ["flow_direction", sensor]
        tmp = dfc[cols].dropna(subset=["flow_direction", sensor]).copy()
        if tmp.empty:
            continue

        rows = []
        for keys, g in tmp.groupby(base_index_cols):
            m_raw = g[sensor].to_numpy(dtype=float)
            theta_raw_deg = g["flow_direction"].to_numpy(dtype=float)
            # センサごとに角度基準を補正（front を基準に、rear は反転）
            if sensor.startswith("rear"):
                theta_raw_deg = 180.0 - theta_raw_deg
            theta_raw = np.deg2rad(theta_raw_deg)
            if len(m_raw) < 1:
                continue

            # ゼロ（またはほぼゼロ）の測定値は無効として除外
            valid_mask = np.isfinite(m_raw) & (np.abs(m_raw) > ZERO_EPS) & np.isfinite(theta_raw)
            if not np.any(valid_mask):
                continue
            m = m_raw[valid_mask]
            theta = theta_raw[valid_mask]

            unique_theta = np.unique(theta)
            # 角度スパンが小さすぎるグループは、u ベクトルを安定に推定できないのでスキップ
            if unique_theta.size >= 2:
                angle_span_rad = float(unique_theta.max() - unique_theta.min())
                angle_span_deg = np.degrees(angle_span_rad)
                if angle_span_deg < ANGLE_SPAN_MIN_DEG:
                    continue
            # 角度が1種類しか無い場合の扱い
            if unique_theta.size == 1:
                if single_angle_mode == "nan":
                    # デフォルト: その点は捨てる
                    continue
                # 'use' モード: その角度方向に流れが向いていると仮定し、U は m の平均
                phi_best = float(unique_theta[0])
                U_best = float(np.nanmean(m))
                if not np.isfinite(U_best) or U_best < 0:
                    continue
            else:
                # 形状: (n_sample, n_phi)
                cos_diff = np.abs(np.cos(theta[:, None] - phi_grid[None, :]))
                denom = np.sum(cos_diff ** 2, axis=0)
                valid = denom > 1e-8
                if not np.any(valid):
                    continue

                num = np.sum(cos_diff * m[:, None], axis=0)
                U = np.zeros_like(phi_grid)
                U[valid] = num[valid] / denom[valid]

                pred = U[None, :] * cos_diff
                err = np.sum((pred - m[:, None]) ** 2, axis=0)
                err[~valid] = np.inf

                idx = int(np.argmin(err))
                phi_best = float(phi_grid[idx])
                U_best = float(U[idx])
                if not np.isfinite(U_best) or U_best < 0:
                    continue

            ux_abs = U_best * abs(np.cos(phi_best))
            uy_abs = U_best * abs(np.sin(phi_best))

            row = {col: val for col, val in zip(base_index_cols, keys)}
            row[f"{sensor}_ux_abs"] = ux_abs
            row[f"{sensor}_uy_abs"] = uy_abs
            row[f"{sensor}_mag"] = U_best
            # メタ情報: サンプル数と角度数（ゼロ除外後）
            row[f"{sensor}_n_samples"] = int(m.size)
            row[f"{sensor}_n_unique_angles"] = int(unique_theta.size)
            row[f"{sensor}_phi_deg"] = float(np.degrees(phi_best))
            rows.append(row)

        if not rows:
            continue

        pivot = pd.DataFrame(rows).set_index(base_index_cols)

        if all_pivot is None:
            all_pivot = pivot
        else:
            all_pivot = all_pivot.join(pivot, how="outer")

    if all_pivot is None or all_pivot.empty:
        raise ValueError("有効な flow_direction とセンサ値の組から再構成できるデータがありません。")

    return all_pivot.reset_index()


def build_long_with_coordinates(components_df: pd.DataFrame) -> pd.DataFrame:
    """センサごとの |u_x|,|u_y|,|u| から、(x,y) 付きのロング形式に変換する。"""
    sensors = ["front_in", "front_out", "rear_in", "rear_out"]

    # インデックス列: センサ由来の列（front_in_*, rear_out_* など）を除いたもの
    meas_prefixes = tuple(f"{s}_" for s in sensors)
    idx_cols = [c for c in components_df.columns if not c.startswith(meas_prefixes)]

    long_parts = []
    for sensor in sensors:
        ux_col = f"{sensor}_ux_abs"
        uy_col = f"{sensor}_uy_abs"
        mag_col = f"{sensor}_mag"
        meta_ns_col = f"{sensor}_n_samples"
        meta_na_col = f"{sensor}_n_unique_angles"
        meta_phi_col = f"{sensor}_phi_deg"
        use_cols = [
            c
            for c in [ux_col, uy_col, mag_col, meta_ns_col, meta_na_col, meta_phi_col]
            if c in components_df.columns
        ]
        if not use_cols:
            continue
        sub = components_df[idx_cols + use_cols].copy()
        # 少なくとも |u| が存在する行のみ使用（無い場合は両成分が揃っていないのでスキップ）
        if mag_col not in sub.columns:
            continue
        sub = sub.dropna(subset=[mag_col])
        if sub.empty:
            continue
        rename_map = {
            ux_col: "ux_abs",
            uy_col: "uy_abs",
            mag_col: "u_mag",
            meta_ns_col: "n_samples",
            meta_na_col: "n_unique_angles",
            meta_phi_col: "phi_deg",
        }
        sub = sub.rename(columns={k: v for k, v in rename_map.items() if k in sub.columns})
        sub["sensor"] = sensor
        long_parts.append(sub)

    if not long_parts:
        raise ValueError("有効な |u| データがありません。")

    df_long = pd.concat(long_parts, ignore_index=True)

    # 座標 (x, y) を計算
    if "flow_distance" not in df_long.columns or "flow_height" not in df_long.columns:
        raise ValueError("flow_distance, flow_height 列が必要です。")

    # flow_distance は [m] 相当なので、可視化では [mm] に変換して扱う
    df_long["flow_distance_mm"] = df_long["flow_distance"] * 1000.0

    def _side_from_sensor(s: str) -> str:
        return "front" if s.startswith("front") else "rear"

    def _io_from_sensor(s: str) -> str:
        return "in" if s.endswith("in") else "out"

    df_long["side"] = df_long["sensor"].apply(_side_from_sensor)
    df_long["io"] = df_long["sensor"].apply(_io_from_sensor)

    # x 座標: front=+flow_distance, rear=-flow_distance
    df_long["x"] = np.where(
        df_long["side"] == "rear",
        -df_long["flow_distance_mm"],
        df_long["flow_distance_mm"],
    )
    # y 座標: in=180-flow_height (上側), out=-flow_height (下側)
    df_long["y"] = np.where(
        df_long["io"] == "in",
        180.0 - df_long["flow_height"],
        -df_long["flow_height"],
    )

    # 符号付き成分も付与:
    # - x: front を +x, rear を -x
    # - y: 上を +y とし、流れは上→下と仮定して常に負方向
    df_long["ux"] = df_long["ux_abs"]
    df_long.loc[df_long["side"] == "rear", "ux"] = -df_long.loc[df_long["side"] == "rear", "ux_abs"]
    df_long["uy"] = -df_long["uy_abs"]

    return df_long


def export_components_long(
    components_df: pd.DataFrame,
    export_path: str,
    row_keys=None,
    col_keys=None,
) -> None:
    """reconstruct_components の出力をロング形式に変換して CSV にエクスポートする。

    1行 = 1つの (distance, flow_distance, flow_height, ..., sensor) に対応し、主な列は:
      - パラメータ列（distance, tilt_angle, ...）
      - sensor: 'front_in', 'front_out', 'rear_in', 'rear_out'
      - u_mag: 推定された |u|
      - ux_abs, uy_abs: 推定された |u_x|, |u_y|
      - ux, uy: front を +x、rear を -x とし、流れが上→下（-y）と仮定して付与した符号付き成分
      - diff_ratio_y_pct: diff_ratio_y と同じ定義の front/rear 差分[%]
          (row_facet, col_facet, io, y) ごとに front/rear をロバスト最大で正規化し、
          (front_norm_y - rear_norm_y) * 100 を各点に付与したもの。
      - phi_deg: 推定された角度（向きなし, [0, 180)）
      - n_samples: この点・センサでフィットに使われたデータ数（ゼロ除外後）
      - n_unique_angles: flow_direction のユニークな個数（ゼロ除外後）
    """
    sensors = ["front_in", "front_out", "rear_in", "rear_out"]
    meas_prefixes = tuple(f"{s}_" for s in sensors)
    idx_cols = [c for c in components_df.columns if not c.startswith(meas_prefixes)]

    long_rows: list[dict] = []
    for sensor in sensors:
        ux_col = f"{sensor}_ux_abs"
        uy_col = f"{sensor}_uy_abs"
        mag_col = f"{sensor}_mag"
        ns_col = f"{sensor}_n_samples"
        na_col = f"{sensor}_n_unique_angles"
        phi_col = f"{sensor}_phi_deg"
        cols = [c for c in [ux_col, uy_col, mag_col, ns_col, na_col, phi_col] if c in components_df.columns]
        if not cols:
            continue
        sub = components_df[idx_cols + cols].copy()
        sub = sub.dropna(subset=[mag_col])
        if sub.empty:
            continue
        for _, r in sub.iterrows():
            row = {k: r[k] for k in idx_cols}
            row["sensor"] = sensor
            ux_abs = r.get(ux_col, np.nan)
            uy_abs = r.get(uy_col, np.nan)
            row["ux_abs"] = ux_abs
            row["uy_abs"] = uy_abs
            row["u_mag"] = r.get(mag_col, np.nan)
            # front 側を +x, rear 側を -x とする符号付き Ux
            if isinstance(sensor, str) and sensor.startswith("rear"):
                row["ux"] = -float(ux_abs) if np.isfinite(ux_abs) else np.nan
            else:
                row["ux"] = float(ux_abs) if np.isfinite(ux_abs) else np.nan
            # 流れは上→下と仮定し、y 正方向を上とすると Uy は常に負
            row["uy"] = -float(uy_abs) if np.isfinite(uy_abs) else np.nan
            row["n_samples"] = int(r.get(ns_col, np.nan)) if ns_col in cols else np.nan
            row["n_unique_angles"] = int(r.get(na_col, np.nan)) if na_col in cols else np.nan
            row["phi_deg"] = r.get(phi_col, np.nan) if phi_col in cols else np.nan
            long_rows.append(row)

    if not long_rows:
        raise ValueError("export_components_long: no valid rows to export.")

    df_export = pd.DataFrame(long_rows)

    # diff_ratio_y と同じ % を、通常エクスポートに追加する
    # - plot_facet_diff_ratio_y() と同じ定義で計算する（ファセット内の (io, y) ごとに正規化）
    # - 計算に必要な列が不足している場合は NaN を出力し、警告を出す
    df_export["diff_ratio_y_pct"] = np.nan
    try:
        tmp = add_facet_labels(df_export.copy(), row_keys, col_keys)

        # merge 後の suffix 衝突を避ける（df_export 側に diff_ratio_y_pct が既にあるため）
        tmp = tmp.drop(columns=["diff_ratio_y_pct"], errors="ignore")

        # センサ名から side/io を付与
        tmp["side"] = np.where(tmp["sensor"].astype(str).str.startswith("front"), "front", "rear")
        tmp["io"] = np.where(tmp["sensor"].astype(str).str.endswith("in"), "in", "out")

        if "flow_distance" not in tmp.columns or "flow_height" not in tmp.columns:
            raise ValueError("flow_distance/flow_height 列がありません。")

        # plot と同じ座標変換（x は mm）
        tmp["flow_distance_mm"] = pd.to_numeric(tmp["flow_distance"], errors="coerce") * 1000.0
        tmp["x"] = np.where(tmp["side"] == "rear", -tmp["flow_distance_mm"], tmp["flow_distance_mm"])
        fh = pd.to_numeric(tmp["flow_height"], errors="coerce")
        tmp["y"] = np.where(tmp["io"] == "in", 180.0 - fh, -fh)

        # front/rear を |x| で折り返してペアリングし、diff_ratio_y を計算
        diff_df = compute_front_rear_diff_fold(tmp)
        group_keys = ["row_facet", "col_facet", "io", "y"]
        front_max = diff_df.groupby(group_keys)["front"].transform(_robust_group_max)
        rear_max = diff_df.groupby(group_keys)["rear"].transform(_robust_group_max)

        diff_df = diff_df.copy()
        with np.errstate(divide="ignore", invalid="ignore"):
            diff_df["front_norm_y"] = np.where(
                np.isfinite(front_max) & (front_max > 0),
                diff_df["front"] / front_max,
                np.nan,
            )
            diff_df["rear_norm_y"] = np.where(
                np.isfinite(rear_max) & (rear_max > 0),
                diff_df["rear"] / rear_max,
                np.nan,
            )
        diff_df["diff_ratio_y_pct"] = (diff_df["front_norm_y"] - diff_df["rear_norm_y"]) * 100.0

        # 各センサ行へ付与（内部キーとして row/col facet を使用。出力列には追加しない）
        tmp["x_abs"] = tmp["x"].abs()
        key_cols = ["row_facet", "col_facet", "io", "x_abs", "y"]
        diff_key = diff_df[key_cols + ["diff_ratio_y_pct"]].copy()
        tmp2 = tmp.merge(diff_key, on=key_cols, how="left")
        df_export["diff_ratio_y_pct"] = tmp2["diff_ratio_y_pct"].to_numpy()
    except Exception as e:
        print(f"Warning: diff_ratio_y_pct の計算に失敗したため NaN を出力します: {e}")

    out_path = Path(export_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    df_export.to_csv(out_path, index=False)
    print(f"Exported reconstructed components (long format) to: {out_path}")


def _format_val(v):
    if pd.isna(v):
        return "nan"
    if isinstance(v, (int, np.integer)):
        return f"{int(v)}"
    try:
        fv = float(v)
        # 角度や距離は整数 or 簡易表記で十分
        if abs(fv - round(fv)) < 1e-6:
            return f"{int(round(fv))}"
        return f"{fv:g}"
    except Exception:
        return str(v)


def add_facet_labels(df_long: pd.DataFrame, row_keys, col_keys) -> pd.DataFrame:
    """行・列ファセット用のラベル列を追加する。"""
    row_keys = [k for k in (row_keys or []) if k in df_long.columns]
    col_keys = [k for k in (col_keys or []) if k in df_long.columns]

    if not row_keys:
        df_long["row_facet"] = "all"
    else:
        def _row_label(r):
            vals = []
            for k in row_keys:
                val = _format_val(r[k])
                if k == "tilt_angle":
                    vals.append(f"θ={val}°")
                elif k == "fold_angle":
                    vals.append(f"Φ={val}°")
                else:
                    vals.append(f"{k}={val}")
            # multi-line label (Excel-like row header)
            return "\n".join(vals)

        df_long["row_facet"] = df_long.apply(_row_label, axis=1)

    if not col_keys:
        df_long["col_facet"] = "all"
    else:
        def _col_label(r):
            vals = []
            for k in col_keys:
                val = _format_val(r[k])
                if k == "wall_spacing":
                    vals.append(f"W={val}")
                else:
                    vals.append(f"{k}={val}")
            return ", ".join(vals)

        df_long["col_facet"] = df_long.apply(_col_label, axis=1)

    return df_long


def _format_num(v: float | int | None, fmt: str) -> str:
    if v is None:
        return "nan"
    try:
        fv = float(v)
    except Exception:
        return "nan"
    if not np.isfinite(fv):
        return "nan"
    return format(fv, fmt)


def _annotate_criteria_on_facet_axes(
    axes: np.ndarray,
    row_levels: list[str],
    col_levels: list[str],
    criteria_df: pd.DataFrame,
) -> None:
    """各ファセットに criteria 集計結果（facet×io×side）を注記する。"""
    need_cols = [
        "row_facet",
        "col_facet",
        "io",
        "side",
        "criteria_field",
        "I_asym",
        "X_center_mm",
        "theta_def_deg",
    ]
    miss = [c for c in need_cols if c not in criteria_df.columns]
    if miss:
        raise ValueError(f"criteria_df に必要な列が不足しています: {', '.join(miss)}")

    # 1 facet = (row_facet, col_facet) 内に、io×side の4行をまとめて書く
    for i, rlab in enumerate(row_levels):
        for j, clab in enumerate(col_levels):
            ax = axes[i, j]
            if not ax.get_visible():
                continue

            sub = criteria_df[
                (criteria_df["row_facet"] == rlab) & (criteria_df["col_facet"] == clab)
            ]
            if sub.empty:
                continue

            # criteria_field は facet 内で同一のはず
            cf = str(sub["criteria_field"].iloc[0])
            lines = [f"criteria={cf}"]
            for io in ["in", "out"]:
                for side in ["front", "rear"]:
                    one = sub[(sub["io"] == io) & (sub["side"] == side)]
                    if one.empty:
                        lines.append(f"{io}/{side}: -")
                        continue
                    # criteria_by_y の場合は y 方向に平均した代表値を表示
                    r = one.agg(
                        {
                            "I_asym": "mean",
                            "X_center_mm": "mean",
                            "theta_def_deg": "mean",
                        }
                    )
                    I = _format_num(r.get("I_asym", np.nan), ".3g")
                    X = _format_num(r.get("X_center_mm", np.nan), ".3g")
                    th = _format_num(r.get("theta_def_deg", np.nan), ".3g")
                    lines.append(f"{io}/{side}: I={I}, X={X}mm, θ={th}°")

            txt = "\n".join(lines)
            ax.text(
                0.02,
                0.98,
                txt,
                transform=ax.transAxes,
                ha="left",
                va="top",
                fontsize=8.5,
                color="white",
                bbox=dict(facecolor="black", alpha=0.35, edgecolor="none", pad=2.0),
                zorder=10,
            )


def _overlay_criteria_marks_on_facet_axes(
    axes: np.ndarray,
    row_levels: list[str],
    col_levels: list[str],
    criteria_df: pd.DataFrame,
    *,
    plot_xcenter: bool,
    plot_theta_def: bool,
    x_is_abs: bool,
) -> None:
    """各ファセットに X_center / theta_def の図示（マーカー/矢印）を重ね描きする。"""
    if (not plot_xcenter) and (not plot_theta_def):
        return

    need_cols = ["row_facet", "col_facet", "io", "side", "X_center_mm", "theta_def_deg"]
    miss = [c for c in need_cols if c not in criteria_df.columns]
    if miss:
        raise ValueError(f"criteria_df に必要な列が不足しています: {', '.join(miss)}")

    # 表示スタイル（ioで色、sideで線種/マーカー）
    io_color = {"in": "#2ca02c", "out": "#9467bd"}  # green / purple
    side_ls = {"front": "-", "rear": "--"}

    for i, rlab in enumerate(row_levels):
        for j, clab in enumerate(col_levels):
            ax = axes[i, j]
            if not ax.get_visible():
                continue

            sub = criteria_df[
                (criteria_df["row_facet"] == rlab) & (criteria_df["col_facet"] == clab)
            ]
            if sub.empty:
                continue

            x0, x1 = ax.get_xlim()
            y0, y1 = ax.get_ylim()
            x_span = x1 - x0 if np.isfinite(x1 - x0) and x1 != x0 else 1.0
            y_span = y1 - y0 if np.isfinite(y1 - y0) and y1 != y0 else 1.0

            # in/out で上下に分けて表示（データ座標）
            y_anchor = {"in": y1 - 0.08 * y_span, "out": y0 + 0.08 * y_span}

            # 矢印の長さ（データ座標でスケール）
            L = 0.12 * min(abs(x_span), abs(y_span))

            for io in ["in", "out"]:
                for side in ["front", "rear"]:
                    one = sub[(sub["io"] == io) & (sub["side"] == side)]
                    if one.empty:
                        continue
                    col = io_color.get(io, "white")
                    ls = side_ls.get(side, "-")

                    # criteria_by_y: y 列がある場合は、y ごとの X_center を線/点列で表示
                    has_y = "y" in one.columns
                    if plot_xcenter and has_y and len(one) > 1:
                        xs = pd.to_numeric(one["X_center_mm"], errors="coerce").to_numpy(dtype=float)
                        ys = pd.to_numeric(one["y"], errors="coerce").to_numpy(dtype=float)
                        m = np.isfinite(xs) & np.isfinite(ys)
                        if np.any(m):
                            xs = xs[m]
                            ys = ys[m]
                            order = np.argsort(ys)
                            xs = xs[order]
                            ys = ys[order]
                            xplot = np.abs(xs) if x_is_abs else xs
                            ax.plot(
                                xplot,
                                ys,
                                color=col,
                                linestyle=ls,
                                linewidth=1.6,
                                marker="o",
                                markersize=3.0,
                                alpha=0.9,
                                zorder=9,
                            )
                    else:
                        # 従来: 代表値で 1 点だけ
                        r = one.agg({"X_center_mm": "mean", "theta_def_deg": "mean"})
                        xc_mm = r.get("X_center_mm", np.nan)
                        th_deg = r.get("theta_def_deg", np.nan)
                        if not np.isfinite(xc_mm):
                            continue
                        x_plot = abs(float(xc_mm)) if x_is_abs else float(xc_mm)
                        if not (min(x0, x1) - 0.05 * x_span <= x_plot <= max(x0, x1) + 0.05 * x_span):
                            continue
                        yy = y_anchor[io]
                        if plot_xcenter:
                            ax.plot(
                                [x_plot, x_plot],
                                [yy - 0.03 * y_span, yy + 0.03 * y_span],
                                color=col,
                                linestyle=ls,
                                linewidth=2.0,
                                alpha=0.95,
                                zorder=9,
                            )
                        if plot_theta_def and np.isfinite(th_deg):
                            th = np.deg2rad(float(th_deg))
                            dx_out = L * np.sin(th)
                            dy = -L * np.cos(th)
                            sign_x = 1.0 if side == "front" else -1.0
                            dx = dx_out * sign_x
                            if x_is_abs:
                                dx = abs(dx)
                            ax.annotate(
                                "",
                                xy=(x_plot + dx, yy + dy),
                                xytext=(x_plot, yy),
                                arrowprops=dict(
                                    arrowstyle="-|>",
                                    color=col,
                                    linewidth=1.6,
                                    linestyle=ls,
                                    alpha=0.95,
                                    shrinkA=0,
                                    shrinkB=0,
                                ),
                                zorder=9,
                            )


def plot_facet_2d(
    df_long: pd.DataFrame,
    mode: str,
    dpi: int,
    output: str | None,
    cmap_in: str = "viridis",
    cmap_out: str = "plasma",
    colorbar_mode: str = "by_io",
    criteria_df: pd.DataFrame | None = None,
    annotate_criteria: bool = False,
    plot_xcenter: bool = False,
    plot_theta_def: bool = False,
):
    """(x,y,|u|) をファセットプロットする。mode='vector_unsigned' の場合は無向きベクトルも重ねる。"""
    if df_long.empty:
        raise ValueError("プロット対象データが空です。")

    row_levels = sorted(df_long["row_facet"].unique().tolist())
    col_levels = sorted(df_long["col_facet"].unique().tolist())
    nrows = len(row_levels)
    ncols = len(col_levels)

    # 軸範囲とベクトルスケールのための全体統計
    x_min = float(df_long["x"].min())
    x_max = float(df_long["x"].max())
    y_min = float(df_long["y"].min())
    y_max = float(df_long["y"].max())
    x_span = x_max - x_min if np.isfinite(x_max - x_min) and x_max != x_min else 1.0
    y_span = y_max - y_min if np.isfinite(y_max - y_min) and y_max != y_min else 1.0
    base_len = 0.15 * min(x_span, y_span)

    # カラーマップ用のスケール（shared/by_io 切替）
    if colorbar_mode == "by_io":
        in_mask = df_long["io"] == "in"
        out_mask = df_long["io"] == "out"
        if in_mask.any():
            u_min_in = float(df_long.loc[in_mask, "u_mag"].min())
            u_max_in = float(df_long.loc[in_mask, "u_mag"].max())
        else:
            u_min_in = u_max_in = 0.0
        if out_mask.any():
            u_min_out = float(df_long.loc[out_mask, "u_mag"].min())
            u_max_out = float(df_long.loc[out_mask, "u_mag"].max())
        else:
            u_min_out = u_max_out = 0.0
        # director ベクトルの長さスケール用に、全体での最大値も保持しておく
        u_max = max(u_max_in, u_max_out)
        if not np.isfinite(u_max) or u_max <= 0:
            raise ValueError("|u| の有効な値がありません。")
        u_min = 0.0
    else:
        u_min = float(df_long["u_mag"].min())
        u_max = float(df_long["u_mag"].max())
        if not np.isfinite(u_max) or u_max <= 0:
            raise ValueError("|u| の有効な値がありません。")

    fig, axes = plt.subplots(
        nrows=nrows,
        ncols=ncols,
        figsize=(4.0 * ncols, 4.0 * nrows),
        sharex=True,
        sharey=True,
    )
    if nrows == 1 and ncols == 1:
        axes = np.array([[axes]])
    elif nrows == 1:
        axes = np.array([axes])
    elif ncols == 1:
        axes = axes[:, np.newaxis]

    # colormap 用に最後に使った scatter を保持（shared/by_io で別々に管理）
    last_scatter_shared = None
    last_scatter_in = None
    last_scatter_out = None

    for i, rlab in enumerate(row_levels):
        for j, clab in enumerate(col_levels):
            ax = axes[i, j]
            sub = df_long[(df_long["row_facet"] == rlab) & (df_long["col_facet"] == clab)]
            if sub.empty:
                ax.set_visible(False)
                continue

            if colorbar_mode == "by_io":
                # in/out それぞれ別カラーマップ・スケールで描画
                sub_in = sub[sub["io"] == "in"]
                if not sub_in.empty and u_max_in > 0:
                    sc_in = ax.scatter(
                        sub_in["x"],
                        sub_in["y"],
                        c=sub_in["u_mag"],
                        cmap=cmap_in,
                        vmin=u_min_in,
                        vmax=u_max_in,
                        s=60,
                        edgecolors="none",
                        zorder=3,
                    )
                    last_scatter_in = sc_in
                sub_out = sub[sub["io"] == "out"]
                if not sub_out.empty and u_max_out > 0:
                    sc_out = ax.scatter(
                        sub_out["x"],
                        sub_out["y"],
                        c=sub_out["u_mag"],
                        cmap=cmap_out,
                        vmin=u_min_out,
                        vmax=u_max_out,
                        s=60,
                        edgecolors="none",
                        zorder=3,
                    )
                    last_scatter_out = sc_out
            else:
                sc = ax.scatter(
                    sub["x"],
                    sub["y"],
                    c=sub["u_mag"],
                    cmap=cmap_out,
                    vmin=u_min,
                    vmax=u_max,
                    s=60,
                    edgecolors="none",
                    zorder=3,
                )
                last_scatter_shared = sc

            if mode == "vector_unsigned":
                # ベクトル場を線分として重ねる（符号付き ux, uy が存在すればそれを使用）
                if "ux" in sub.columns and "uy" in sub.columns:
                    sub_vec = sub.dropna(subset=["ux", "uy", "u_mag"])
                    use_abs = False
                else:
                    # 後方互換用（古いCSVなど）
                    sub_vec = sub.dropna(subset=["ux_abs", "uy_abs", "u_mag"])
                    use_abs = True
                for _, row in sub_vec.iterrows():
                    if use_abs:
                        ux = float(row["ux_abs"])
                        uy = float(row["uy_abs"])
                    else:
                        ux = float(row["ux"])
                        uy = float(row["uy"])
                    um = float(row["u_mag"])
                    if um <= 0:
                        continue
                    dx = ux / um
                    dy = uy / um
                    L = base_len * (um / u_max)
                    x0 = row["x"] - 0.5 * L * dx
                    x1 = row["x"] + 0.5 * L * dx
                    y0 = row["y"] - 0.5 * L * dy
                    y1 = row["y"] + 0.5 * L * dy
                    ax.plot(
                        [x0, x1],
                        [y0, y1],
                        color="white",
                        linewidth=0.7,
                        alpha=0.9,
                        zorder=4,
                    )

            if i == nrows - 1:
                ax.set_xlabel("x [mm] (front=+, rear=-)")
            if j == 0:
                ax.set_ylabel("y [mm]")
            # facet titles are handled outside the axes
            ax.set_title("")

    for ax in axes.ravel():
        if ax.get_visible():
            ax.set_xlim(x_min - 0.05 * x_span, x_max + 0.05 * x_span)
            ax.set_ylim(y_min - 0.05 * y_span, y_max + 0.05 * y_span)
            ax.set_aspect("equal", adjustable="box")

    if annotate_criteria and criteria_df is not None and not criteria_df.empty:
        _annotate_criteria_on_facet_axes(axes, row_levels, col_levels, criteria_df)
    if criteria_df is not None and not criteria_df.empty:
        _overlay_criteria_marks_on_facet_axes(
            axes,
            row_levels,
            col_levels,
            criteria_df,
            plot_xcenter=plot_xcenter,
            plot_theta_def=plot_theta_def,
            x_is_abs=False,
        )

    # adjust margins so that row/column labelsとカラーバーが収まるようにする
    # 左に十分な余白を確保（行ラベル用）、右はカラーバー用
    fig.subplots_adjust(left=0.35, right=0.82, top=0.9, bottom=0.12)

    # place facet labels outside the axes like Excel (row labels on the left, column labels on top)
    fig.canvas.draw()  # ensure positions are updated
    # column labels (top)
    for j, clab in enumerate(col_levels):
        ax = axes[0, j]
        pos = ax.get_position()
        x_center = 0.5 * (pos.x0 + pos.x1)
        # fix y-position so it does not collide with the colorbar
        y_top = pos.y1 + 0.015
        fig.text(x_center, y_top, clab, ha="center", va="bottom", fontsize=11)
    # row labels (left) — axes 座標系で描画し、y 軸ラベルよりも外側に置く
    # これにより「row label -> y-axis label -> plot」の順になる
    for i, rlab in enumerate(row_levels):
        ax = axes[i, 0]
        # x をさらに左 (-0.75) にして、フォントサイズも他と揃えて少し大きく
        ax.text(
            -0.75,
            0.5,
            rlab,
            transform=ax.transAxes,
            ha="right",
            va="center",
            fontsize=12,
        )

    if colorbar_mode == "by_io":
        # in/out 用に上下2本のカラーバーを配置
        if last_scatter_in is not None:
            cax_in = fig.add_axes([0.86, 0.55, 0.02, 0.27])
            cbar_in = fig.colorbar(last_scatter_in, cax=cax_in, orientation="vertical")
            cbar_in.set_label("|u| in [m/s]")
        if last_scatter_out is not None:
            cax_out = fig.add_axes([0.86, 0.18, 0.02, 0.27])
            cbar_out = fig.colorbar(last_scatter_out, cax=cax_out, orientation="vertical")
            cbar_out.set_label("|u| out [m/s]")
    else:
        if last_scatter_shared is not None:
            # single shared colorbar
            cax = fig.add_axes([0.86, 0.18, 0.02, 0.64])
            cbar = fig.colorbar(last_scatter_shared, cax=cax, orientation="vertical")
            cbar.set_label("|u| [m/s] (reconstructed magnitude)")

    if output:
        out_path = Path(output)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        fig.savefig(str(out_path), dpi=dpi, bbox_inches="tight")
        print(f"保存しました: {out_path}")
    else:
        plt.show()


    # legacy helper _robust_group_max はモジュール先頭の実装に置き換え済み
    # ここにあった旧定義は削除しました（DIFF_R 参照などは使用されません）
def plot_facet_scalar_norm(df_long: pd.DataFrame, dpi: int, output: str | None):
    """|u| を in/out 別のロバスト最大値で正規化し、0〜100% のスカラー場として表示するモード。"""
    if df_long.empty:
        raise ValueError("プロット対象データが空です。")

    row_levels = sorted(df_long["row_facet"].unique().tolist())
    col_levels = sorted(df_long["col_facet"].unique().tolist())
    nrows = len(row_levels)
    ncols = len(col_levels)

    x_min = float(df_long["x"].min())
    x_max = float(df_long["x"].max())
    y_min = float(df_long["y"].min())
    y_max = float(df_long["y"].max())
    x_span = x_max - x_min if np.isfinite(x_max - x_min) and x_max != x_min else 1.0
    y_span = y_max - y_min if np.isfinite(y_max - y_min) and y_max != y_min else 1.0

    in_mask = df_long["io"] == "in"
    out_mask = df_long["io"] == "out"

    def _robust_max(vals: pd.Series) -> float | None:
        vals = vals.dropna()
        if vals.empty:
            return None
        q1 = vals.quantile(0.25)
        q3 = vals.quantile(0.75)
        iqr = q3 - q1
        if np.isfinite(iqr) and iqr > 0:
            cand = q3 + DIFF_RATIO_IQR_K * iqr
            mx = float(vals.max())
            m = float(min(mx, cand))
        else:
            m = float(vals.max())
        if not np.isfinite(m) or m <= 0:
            return None
