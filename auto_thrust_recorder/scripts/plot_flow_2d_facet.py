def compute_front_rear_diff_fold(df_long: pd.DataFrame) -> pd.DataFrame:
    """front/rear を |x| で折り返し、|u_front| - |u_rear| を計算したテーブルを返す。"""
    if "side" not in df_long.columns:
        raise ValueError("df_long に 'side' 列がありません。")
    if "io" not in df_long.columns:
        raise ValueError("df_long に 'io' 列がありません。")

    dfw = df_long.copy()
    dfw["x_abs"] = dfw["x"].abs()

    index_cols = ["row_facet", "col_facet", "io", "x_abs", "y"]
    for c in index_cols:
        if c not in dfw.columns:
            raise ValueError(f"df_long に '{c}' 列がありません。")

    pivot = (
        dfw.pivot_table(
            index=index_cols,
            columns="side",
            values="u_mag",
            aggfunc="mean",
        )
        .reset_index()
    )
    if "front" not in pivot.columns or "rear" not in pivot.columns:
        raise ValueError("front/rear の両方のデータが不足しており、diff_fold を計算できません。")

    pivot = pivot.dropna(subset=["front", "rear"]).copy()
    if pivot.empty:
        raise ValueError("front/rear の両方が揃った点がありません。")

    pivot["diff"] = pivot["front"] - pivot["rear"]
    return pivot


