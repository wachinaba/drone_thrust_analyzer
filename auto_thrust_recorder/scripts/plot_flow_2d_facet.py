def plot_facet_diff_ratio(
    df_long: pd.DataFrame,
    dpi: int,
    output: str | None,
    criteria_df: pd.DataFrame | None = None,
    annotate_criteria: bool = False,
    plot_xcenter: bool = False,
    plot_theta_def: bool = False,
):
    """rear を front 側に折り返し、(front - rear) / mean(front, rear) を割合で表示するファセットプロット。"""
    diff_df = compute_front_rear_diff_fold(df_long)

    row_levels = sorted(diff_df["row_facet"].unique().tolist())
    col_levels = sorted(diff_df["col_facet"].unique().tolist())
    nrows = len(row_levels)
    ncols = len(col_levels)

    x_min = float(diff_df["x_abs"].min())
    x_max = float(diff_df["x_abs"].max())
    y_min = float(diff_df["y"].min())
    y_max = float(diff_df["y"].max())
    x_span = x_max - x_min if np.isfinite(x_max - x_min) and x_max != x_min else 1.0
    y_span = y_max - y_min if np.isfinite(y_max - y_min) and y_max != y_min else 1.0

    # 各点ごとに割合 r = (front - rear) / mean(front, rear) を計算（%単位）
    denom = 0.5 * (diff_df["front"] + diff_df["rear"])
    valid = denom.abs() > ZERO_EPS
    diff_df = diff_df.copy()
    diff_df["ratio"] = np.nan
    diff_df.loc[valid, "ratio"] = (diff_df.loc[valid, "diff"] / denom.loc[valid]) * 100.0

    # in/out 別に IQR ベースのロバストスケーリングでカラーバー範囲を決定
    in_mask = diff_df["io"] == "in"
    out_mask = diff_df["io"] == "out"

    def _compute_limits(mask: pd.Series) -> tuple[float, float] | tuple[None, None]:
        vals = diff_df.loc[mask, "ratio"].dropna()
        if vals.empty:
            return None, None
        q1 = vals.quantile(0.25)
        q3 = vals.quantile(0.75)
        iqr = q3 - q1
        if np.isfinite(iqr) and iqr > 0:
            L = q1 - DIFF_RATIO_IQR_K * iqr
            U = q3 + DIFF_RATIO_IQR_K * iqr
        else:
            L, U = float(vals.min()), float(vals.max())
        lim = max(abs(L), abs(U))
        if not np.isfinite(lim) or lim == 0:
            lim = max(abs(float(vals.min())), abs(float(vals.max())))
        if not np.isfinite(lim) or lim == 0:
            return None, None
        return -lim, lim

    vmin_in, vmax_in = _compute_limits(in_mask)
    vmin_out, vmax_out = _compute_limits(out_mask)

    if vmin_in is None and vmin_out is None:
        raise ValueError("diff_ratio の有効な割合データがありません。")

    fig, axes = plt.subplots(
        nrows=nrows,
        ncols=ncols,
        figsize=(4.0 * ncols, 4.0 * nrows),
        sharex=True,
        sharey=True,
    )
    if nrows == 1 and ncols == 1:
        axes = np.array([[axes]])
    elif nrows == 1:
        axes = np.array([axes])
    elif ncols == 1:
        axes = axes[:, np.newaxis]

    last_scatter_in = None
    last_scatter_out = None

    for i, rlab in enumerate(row_levels):
        for j, clab in enumerate(col_levels):
            ax = axes[i, j]
            sub = diff_df[
                (diff_df["row_facet"] == rlab)
                & (diff_df["col_facet"] == clab)
            ]
            if sub.empty:
                ax.set_visible(False)
                continue

            sub_in = sub[sub["io"] == "in"]
            if vmin_in is not None and not sub_in.empty:
                sc_in = ax.scatter(
                    sub_in["x_abs"],
                    sub_in["y"],
                    c=sub_in["ratio"],
                    cmap="coolwarm",
                    vmin=vmin_in,
                    vmax=vmax_in,
                    s=60,
                    edgecolors="none",
                )
                last_scatter_in = sc_in

            sub_out = sub[sub["io"] == "out"]
            if vmin_out is not None and not sub_out.empty:
                sc_out = ax.scatter(
                    sub_out["x_abs"],
                    sub_out["y"],
                    c=sub_out["ratio"],
                    cmap="coolwarm",
                    vmin=vmin_out,
                    vmax=vmax_out,
                    s=60,
                    edgecolors="none",
                )
                last_scatter_out = sc_out

            if i == nrows - 1:
                ax.set_xlabel("x [mm] (|x|, front/rear folded)")
            if j == 0:
                ax.set_ylabel("y [mm]")
            ax.set_title("")

    for ax in axes.ravel():
        if ax.get_visible():
            ax.set_xlim(x_min - 0.05 * x_span, x_max + 0.05 * x_span)
            ax.set_ylim(y_min - 0.05 * y_span, y_max + 0.05 * y_span)
            ax.set_aspect("equal", adjustable="box")

    if annotate_criteria and criteria_df is not None and not criteria_df.empty:
        _annotate_criteria_on_facet_axes(axes, row_levels, col_levels, criteria_df)
    if criteria_df is not None and not criteria_df.empty:
        _overlay_criteria_marks_on_facet_axes(
            axes,
            row_levels,
            col_levels,
            criteria_df,
            plot_xcenter=plot_xcenter,
            plot_theta_def=plot_theta_def,
            x_is_abs=True,
        )

    fig.subplots_adjust(left=0.35, right=0.82, top=0.9, bottom=0.12)
    fig.canvas.draw()

    for j, clab in enumerate(col_levels):
        ax = axes[0, j]
        pos = ax.get_position()
        x_center = 0.5 * (pos.x0 + pos.x1)
        y_top = pos.y1 + 0.015
        fig.text(x_center, y_top, clab, ha="center", va="bottom", fontsize=11)

    for i, rlab in enumerate(row_levels):
        ax = axes[i, 0]
        ax.text(
            -0.75,
            0.5,
            rlab,
            transform=ax.transAxes,
            ha="right",
            va="center",
            fontsize=12,
        )

    # in/out 用に上下2本のカラーバー（割合用）
    if last_scatter_in is not None and vmin_in is not None:
        cax_in = fig.add_axes([0.86, 0.55, 0.02, 0.27])
        cbar_in = fig.colorbar(last_scatter_in, cax=cax_in, orientation="vertical")
        cbar_in.set_label("diff ratio [%] (in)")
    if last_scatter_out is not None and vmin_out is not None:
        cax_out = fig.add_axes([0.86, 0.18, 0.02, 0.27])
        cbar_out = fig.colorbar(last_scatter_out, cax=cax_out, orientation="vertical")
        cbar_out.set_label("diff ratio [%] (out)")

    if output:
        out_path = Path(output)
        out_path.parent.mkdir(parents=True, exist_ok=True)
