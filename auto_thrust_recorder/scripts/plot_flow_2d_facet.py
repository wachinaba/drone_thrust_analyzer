# 角度フィッティングに最低限必要とみなす flow_direction のスパン [deg]
ANGLE_SPAN_MIN_DEG = 20.0
# センサ値を「ゼロ」とみなして無視するためのしきい値
ZERO_EPS = 1e-6
# diff_ratio 用: IQR によるロバストスケーリングの係数
DIFF_RATIO_IQR_K = 1.5
# 互換用プレースホルダ（古いコード片で参照されているが、実質的には未使用）
DIFF_RATIO_MIN_DEG = DIFF_RATIO_IQR_K


def _robust_group_max(s: pd.Series) -> float:
    """グループ内の値からロバストな最大値を計算するヘルパー。

    - NaN / 非有限値 / ゼロ付近 (<= ZERO_EPS) は無視する
    - IQR を用いて極端な外れ値の影響を抑えた最大値を返す
    """
    s = s[np.isfinite(s) & (s > ZERO_EPS)]
    if s.empty:
        return np.nan
    q1 = s.quantile(0.25)
    q3 = s.quantile(0.75)
    iqr = q3 - q1
    if np.isfinite(iqr) and iqr > 0:
        thresh = q3 + DIFF_RATIO_IQR_K * iqr
        s = s[s <= thresh]
        if s.empty:
            return np.nan
    return float(s.max()) if not s.empty else np.nan


