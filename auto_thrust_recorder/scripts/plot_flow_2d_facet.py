def plot_facet_diff_ratio_norm(
    df_long: pd.DataFrame,
    dpi: int,
    output: str | None,
    criteria_df: pd.DataFrame | None = None,
    annotate_criteria: bool = False,
    plot_xcenter: bool = False,
    plot_theta_def: bool = False,
):
    """front/rear を |x| で折り返し、各点ごとに
       r = (front/front_max_robust - rear/rear_max_robust) * 100 [%]
       をプロットするモード。

    front_max_robust, rear_max_robust は in/out 別に IQR ベースでロバストに決定する。
    """
    diff_df = compute_front_rear_diff_fold(df_long)

    row_levels = sorted(diff_df["row_facet"].unique().tolist())
    col_levels = sorted(diff_df["col_facet"].unique().tolist())
    nrows = len(row_levels)
    ncols = len(col_levels)

    x_min = float(diff_df["x_abs"].min())
    x_max = float(diff_df["x_abs"].max())
    y_min = float(diff_df["y"].min())
    y_max = float(diff_df["y"].max())
    x_span = x_max - x_min if np.isfinite(x_max - x_min) and x_max != x_min else 1.0
    y_span = y_max - y_min if np.isfinite(y_max - y_min) and y_max != y_min else 1.0

    # in/out 別に front/rear のロバスト最大値を計算
    in_mask = diff_df["io"] == "in"
    out_mask = diff_df["io"] == "out"

    def _robust_max(vals: pd.Series) -> float | None:
        vals = vals.dropna()
        if vals.empty:
            return None
        q1 = vals.quantile(0.25)
        q3 = vals.quantile(0.75)
        iqr = q3 - q1
        if np.isfinite(iqr) and iqr > 0:
            cand = q3 + DIFF_RATIO_IQR_K * iqr
            mx = float(vals.max())
            m = float(min(mx, cand))
        else:
            m = float(vals.max())
        if not np.isfinite(m) or m <= 0:
            return None
        return m

    front_max_in = _robust_max(diff_df.loc[in_mask, "front"]) if in_mask.any() else None
    rear_max_in = _robust_max(diff_df.loc[in_mask, "rear"]) if in_mask.any() else None
    front_max_out = _robust_max(diff_df.loc[out_mask, "front"]) if out_mask.any() else None
    rear_max_out = _robust_max(diff_df.loc[out_mask, "rear"]) if out_mask.any() else None

    if all(m is None for m in [front_max_in, rear_max_in, front_max_out, rear_max_out]):
        raise ValueError("diff_ratio_norm 用のロバスト最大値が計算できません。")

    diff_df = diff_df.copy()
    diff_df["ratio_norm"] = np.nan

    # in 側
    if in_mask.any() and front_max_in and rear_max_in:
        sub = diff_df.loc[in_mask].copy()
        f_norm = sub["front"] / front_max_in
        r_norm = sub["rear"] / rear_max_in
        diff_df.loc[in_mask, "ratio_norm"] = (f_norm - r_norm) * 100.0

    # out 側
    if out_mask.any() and front_max_out and rear_max_out:
        sub = diff_df.loc[out_mask].copy()
        f_norm = sub["front"] / front_max_out
        r_norm = sub["rear"] / rear_max_out
        diff_df.loc[out_mask, "ratio_norm"] = (f_norm - r_norm) * 100.0

    # IQR ベースで表示範囲を決定
    def _compute_limits_ratio(mask: pd.Series) -> tuple[float, float] | tuple[None, None]:
        vals = diff_df.loc[mask, "ratio_norm"].dropna()
        if vals.empty:
            return None, None
        q1 = vals.quantile(0.25)
        q3 = vals.quantile(0.75)
        iqr = q3 - q1
        if np.isfinite(iqr) and iqr > 0:
            L = q1 - DIFF_RATIO_IQR_K * iqr
            U = q3 + DIFF_RATIO_IQR_K * iqr
