def _estimate_k_and_dx_for_group(
    g: pd.DataFrame,
    *,
    anchors: list[int],
    x_max_mm: float,
    x_step_mm: float,
) -> tuple[float, dict[int, float], float, int]:
    """単一グループ（scope単位）の (Δx, K1..K4) を同時推定する。

    - Δx はグリッド探索
    - K は logK の線形最小二乗（anchors の logK=0 を固定）
    - V_meas は u_mag を使用
    返り値: (best_dx, K_by_id(1..4), best_sse, n_eq)
    """
    if g.empty:
        return 0.0, {1: 1.0, 2: 1.0, 3: 1.0, 4: 1.0}, float("nan"), 0
    if x_step_mm <= 0 or not np.isfinite(x_step_mm):
        x_step_mm = 1.0
    if x_max_mm <= 0 or not np.isfinite(x_max_mm):
        x_max_mm = 0.0

    # 必須列
    for c in ["direction", "sensor", "x", "u_mag"]:
        if c not in g.columns:
            return 0.0, {1: 1.0, 2: 1.0, 3: 1.0, 4: 1.0}, float("nan"), 0

    # anchors（2つ想定）
    anchors = [int(a) for a in anchors]
    anchors = [a for a in anchors if a in [1, 2, 3, 4]]
    anchors = sorted(list(dict.fromkeys(anchors)))
    if len(anchors) < 1:
        anchors = [1]

    unknown_ids = [i for i in [1, 2, 3, 4] if i not in anchors]
    # 係数行列用
    id_to_idx = {pid: idx for idx, pid in enumerate(unknown_ids)}

    n = int(np.floor(x_max_mm / x_step_mm)) if x_max_mm > 0 else 0
    grid = np.arange(-n * x_step_mm, n * x_step_mm + 0.5 * x_step_mm, x_step_mm, dtype=float) if n > 0 else np.array([0.0])

    best_dx = 0.0
    best_sse = np.inf
    best_logk = np.zeros(len(unknown_ids), dtype=float)
    best_ne = 0

    # 方向の存在確認
    dirs = set(g["direction"].dropna().astype(str).unique().tolist())
    if (DIR_FRONT not in dirs) or (DIR_BACK_REVERSED not in dirs):
        # 片方しか無いなら推定不可（Kはそのまま）
        k0 = {1: 1.0, 2: 1.0, 3: 1.0, 4: 1.0}
        return 0.0, k0, float("nan"), 0

    for dx in grid:
        A_rows: list[list[float]] = []
        b_vals: list[float] = []

        for s in SENSOR_NAMES:
            sf = g[(g["direction"].astype(str) == DIR_FRONT) & (g["sensor"].astype(str) == s)]
            sb = g[(g["direction"].astype(str) == DIR_BACK_REVERSED) & (g["sensor"].astype(str) == s)]
            if sf.empty or sb.empty:
                continue

            xf = pd.to_numeric(sf["x"], errors="coerce").to_numpy(dtype=float)
            uf = pd.to_numeric(sf["u_mag"], errors="coerce").to_numpy(dtype=float)
            xb = pd.to_numeric(sb["x"], errors="coerce").to_numpy(dtype=float) + float(dx)
            ub = pd.to_numeric(sb["u_mag"], errors="coerce").to_numpy(dtype=float)

            mf = np.isfinite(xf) & np.isfinite(uf) & (uf > ZERO_EPS)
            mb = np.isfinite(xb) & np.isfinite(ub) & (ub > ZERO_EPS)
            if mf.sum() < 2 or mb.sum() < 2:
                continue
            xf = xf[mf]
            uf = uf[mf]
            xb = xb[mb]
            ub = ub[mb]

            of = np.argsort(xf)
            ob = np.argsort(xb)
            xf = xf[of]
            uf = uf[of]
            xb = xb[ob]
            ub = ub[ob]

            lo = max(float(np.min(xf)), float(np.min(xb)))
            hi = min(float(np.max(xf)), float(np.max(xb)))
            if not np.isfinite(lo) or not np.isfinite(hi) or hi <= lo:
                continue
            mask = (xf >= lo) & (xf <= hi)
            if mask.sum() < 2:
                continue

            ub_i = np.interp(xf[mask], xb, ub)
            m2 = np.isfinite(ub_i) & (ub_i > ZERO_EPS)
            if m2.sum() < 2:
                continue

            # log比
            rr = np.log(uf[mask][m2]) - np.log(ub_i[m2])

            id_f = _phys_id(DIR_FRONT, s)
            id_b = _phys_id(DIR_BACK_REVERSED, s)
            if id_f is None or id_b is None:
                continue

            # (logK_id_f - logK_id_b) = rr
            # unknownに移し、anchorは0として扱う（K_anchor=1固定）
            for val in rr:
                row = [0.0] * len(unknown_ids)
                # unknown側の係数
                if id_f in id_to_idx:
                    row[id_to_idx[id_f]] += 1.0
                # id_b
                if id_b in id_to_idx:
                    row[id_to_idx[id_b]] -= 1.0

                # anchorは logK=0 なので定数項調整は不要
                A_rows.append(row)
                b_vals.append(float(val))

        if len(b_vals) < max(2, len(unknown_ids)):
            continue

        A = np.asarray(A_rows, dtype=float)
        b = np.asarray(b_vals, dtype=float)

        # 最小二乗
        try:
            p, *_ = np.linalg.lstsq(A, b, rcond=None)
        except Exception:
            continue

        res = A @ p - b
        sse = float(np.sum(res**2))
        if sse < best_sse:
            best_sse = sse
            best_dx = float(dx)
            best_logk = p.copy()
            best_ne = int(len(b_vals))

    # 推定不能ならデフォルト
    if not np.isfinite(best_sse):
        best_sse = float("nan")

    K_by_id = {1: 1.0, 2: 1.0, 3: 1.0, 4: 1.0}
    # anchorsは1
    for aid in anchors:
        K_by_id[int(aid)] = 1.0
    # unknown
    for pid in unknown_ids:
        idx = id_to_idx[pid]
        v = float(np.exp(best_logk[idx])) if np.isfinite(best_logk[idx]) else np.nan
        K_by_id[int(pid)] = v

    return best_dx, K_by_id, best_sse, best_ne


def fit_sensor_k_and_dx(
    df_long: pd.DataFrame,
    *,
    scope: str,
    anchors: list[int],
    x_max_mm: float,
    x_step_mm: float,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """scope単位でKとjoint Δxを推定し、df_longへK補正（u_mag/ux_abs/uy_abs）を適用する。

    返り値: (補正後df_long, 推定結果テーブル)
    """
    dfk = _add_scope_key_column(df_long, scope)
    out_rows: list[dict] = []
    key_to_K: dict[str, dict[int, float]] = {}
    key_to_dx: dict[str, float] = {}

    for key, g in dfk.groupby("scope_key", dropna=False):
        dx, K_by_id, sse, ne = _estimate_k_and_dx_for_group(
            g,
            anchors=anchors,
            x_max_mm=float(x_max_mm),
            x_step_mm=float(x_step_mm),
        )
        key_to_K[str(key)] = K_by_id
        key_to_dx[str(key)] = dx
        out_rows.append(
            {
                "scope_key": str(key),
                "dx_joint_mm": dx,
                "K1": K_by_id.get(1, np.nan),
                "K2": K_by_id.get(2, np.nan),
                "K3": K_by_id.get(3, np.nan),
                "K4": K_by_id.get(4, np.nan),
                "sse": sse,
                "n_eq": ne,
            }
        )

    df_out = pd.DataFrame(out_rows)

    # K補正を適用
    def _row_phys_id(r: pd.Series) -> float:
        pid = _phys_id(str(r.get("direction")), str(r.get("sensor")))
        return float(pid) if pid is not None else np.nan

    dfk["phys_id"] = dfk.apply(_row_phys_id, axis=1)
    dfk["K_est"] = np.nan
    for key, K_by_id in key_to_K.items():
        m = dfk["scope_key"].astype(str) == str(key)
        if not m.any():
            continue
        # pidごとにK割当
        for pid, kval in K_by_id.items():
            mm = m & (dfk["phys_id"] == float(pid))
            if mm.any():
                dfk.loc[mm, "K_est"] = float(kval) if np.isfinite(kval) else np.nan

    # u_mag/ux_abs/uy_abs を補正（V_actual = V_meas / K）
    for c in ["u_mag", "ux_abs", "uy_abs"]:
        if c in dfk.columns:
            with np.errstate(divide="ignore", invalid="ignore"):
                dfk[c] = np.where(
                    np.isfinite(dfk["K_est"]) & (dfk["K_est"] > 0),
                    pd.to_numeric(dfk[c], errors="coerce") / dfk["K_est"],
                    np.nan,
                )

    # 内部列を落として戻す
    df_corr = dfk.drop(columns=["scope_key", "phys_id", "K_est"], errors="ignore")
    return df_corr, df_out


def _centroid_x_trapz(x: np.ndarray, y: np.ndarray, *, weight_mode: str) -> float:
    """線の重心 Xc を数値積分で求める。

    weight_mode:
      - 'positive': f = max(y, 0)
      - 'abs': f = abs(y)
    """
    if weight_mode not in ["positive", "abs"]:
        raise ValueError(f"unknown weight_mode: {weight_mode}")
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)
    m = np.isfinite(x) & np.isfinite(y)
    if m.sum() < 2:
        return np.nan
    x = x[m]
    y = y[m]
    o = np.argsort(x)
    x = x[o]
    y = y[o]
    if weight_mode == "abs":
        f = np.abs(y)
    else:
        f = np.maximum(y, 0.0)
    A = float(np.trapz(f, x))
    if not np.isfinite(A) or A <= 0:
        return np.nan
    Ax = float(np.trapz(x * f, x))
    xc = Ax / A
    return float(xc) if np.isfinite(xc) else np.nan


def add_feature_columns(df_long: pd.DataFrame) -> pd.DataFrame:
    """norm / norm_y 等の特徴量列を追加する。"""
    df = df_long.copy()

    # ロバスト最大（分母）の算出は、まず direction を平均した「平均系列（平均線の元データ）」を作ってから行う。
    # - direction=front/back_reversed 間で点数が異なる場合でも、ここでは物理点（y, flow_distance）単位で平均を取る。
    need_cols = ["col_facet", "io", "side", "y", "flow_distance_mm", "direction", "u_mag", "ux_abs", "uy_abs"]
    miss = [c for c in need_cols if c not in df.columns]
    if miss:
        raise ValueError(f"add_feature_columns: 必要な列が不足しています: {', '.join(miss)}")

    # direction を潰した平均系列（=平均線の元になる点列）
    # ここでは x ではなく flow_distance_mm をキーにしておく（x-offset などの表示補正に影響されない）
    df_mean_dir = (
        df.groupby(["col_facet", "io", "side", "y", "flow_distance_mm"], dropna=False)[["u_mag", "ux_abs", "uy_abs"]]
        .mean()
        .reset_index()
    )

    # io ごとのロバスト最大（norm 用）— 平均系列から計算
    max_io = df_mean_dir.groupby(["io"])["u_mag"].transform(_robust_max_iqr)
    denom_io = df_mean_dir[["col_facet", "io", "side", "y", "flow_distance_mm"]].copy()
    denom_io["max_io_u"] = max_io.to_numpy()
    # io単位なのでテーブル化してmapする
    max_io_tbl = denom_io.dropna(subset=["io", "max_io_u"]).drop_duplicates(subset=["io"])[["io", "max_io_u"]]
    io_to_max = dict(zip(max_io_tbl["io"].astype(str), max_io_tbl["max_io_u"].astype(float), strict=False))
    io_key = df["io"].astype(str)
    max_io_u = io_key.map(io_to_max)
    with np.errstate(divide="ignore", invalid="ignore"):
        df["norm"] = np.where(np.isfinite(max_io_u) & (max_io_u > 0), df["u_mag"] / max_io_u * 100.0, np.nan)

    # (col_facet, io, y) ごとのロバスト最大（norm_y 用: facet 内で正規化）
    if "col_facet" not in df.columns:
        raise ValueError("norm_y の計算には col_facet 列が必要です（add_col_facet_label の後に呼んでください）。")
    max_io_y = df_mean_dir.groupby(["col_facet", "io", "y"])["u_mag"].transform(_robust_max_iqr)
    key_tbl = df_mean_dir[["col_facet", "io", "y"]].copy()
    key_tbl["max_io_y_u"] = max_io_y.to_numpy()
    key_tbl = key_tbl.dropna(subset=["col_facet", "io", "y"]).drop_duplicates(subset=["col_facet", "io", "y"])
    mi = pd.MultiIndex.from_frame(key_tbl[["col_facet", "io", "y"]])
    s_max_io_y = pd.Series(key_tbl["max_io_y_u"].to_numpy(dtype=float), index=mi)
    max_io_y_u = s_max_io_y.reindex(pd.MultiIndex.from_frame(df[["col_facet", "io", "y"]])).to_numpy()
    with np.errstate(divide="ignore", invalid="ignore"):
        df["norm_y"] = np.where(np.isfinite(max_io_y_u) & (max_io_y_u > 0), df["u_mag"] / max_io_y_u * 100.0, np.nan)

    # *_norm_o: facet(col_facet) ごとの out のロバスト最大を基準に正規化（%）
    out_mask_mean = df_mean_dir["io"].astype(str) == "out"
    if out_mask_mean.any():
        for src, dst in [
            ("u_mag", "u_norm_o"),
            ("ux_abs", "ux_norm_o"),
            ("uy_abs", "uy_norm_o"),
        ]:
            # outのみでロバスト最大を計算し、facetに紐付けて全行へ適用
            facet_max = (
                df_mean_dir.loc[out_mask_mean]
                .groupby("col_facet")[src]
                .apply(_robust_max_iqr)
            )
            denom = df["col_facet"].map(facet_max)
            with np.errstate(divide="ignore", invalid="ignore"):
                df[dst] = np.where(np.isfinite(denom) & (denom > 0), df[src] / denom * 100.0, np.nan)
    else:
        df["u_norm_o"] = np.nan
        df["ux_norm_o"] = np.nan
        df["uy_norm_o"] = np.nan

    return df


def _estimate_x_offset_for_io(
    df_long: pd.DataFrame,
    *,
    io: str,
    y_value: float | None,
    col_facet_value: str | None,
    feature: str,
    max_mm: float,
    step_mm: float,
) -> float:
    """io(in/out) ごとに、direction=front を基準として back_reversed を x シフトする Δx を推定する。

    - 比較は (col_facet, y, side) ごとに行い、グループ内の MSE を合算して最小化
    - diff モードでも fit は常に signed x（x）で行う（ユーザー指定）
    """
    if max_mm <= 0 or not np.isfinite(max_mm):
        return 0.0
    if step_mm <= 0 or not np.isfinite(step_mm):
        step_mm = 1.0

    # fit は常に signed x
    xcol = "x"
    df0 = df_long.copy()
    df0 = df0[df0["io"].astype(str) == str(io)]
    if y_value is not None:
        # y は変換後の値（float）をキーとして一致させる
        df0 = df0[pd.to_numeric(df0["y"], errors="coerce") == float(y_value)]
    if col_facet_value is not None:
        df0 = df0[df0["col_facet"].astype(str) == str(col_facet_value)]
    df0 = df0[np.isfinite(pd.to_numeric(df0[xcol], errors="coerce"))]
    df0 = df0[np.isfinite(pd.to_numeric(df0[feature], errors="coerce"))]

    if df0.empty:
        return 0.0

    # 必須の direction が揃っていなければ推定不可
    dirs = set(df0["direction"].dropna().astype(str).unique().tolist())
    if (DIR_FRONT not in dirs) or (DIR_BACK_REVERSED not in dirs):
        return 0.0

    # 探索グリッド（mm）
    n = int(np.floor(max_mm / step_mm))
    grid = np.arange(-n * step_mm, n * step_mm + 0.5 * step_mm, step_mm, dtype=float)
    if grid.size == 0:
        return 0.0

    best_dx = 0.0
    best_err = np.inf

    # フィルタで固定している次元は group_keys から外す
    group_keys = ["col_facet", "y", "side"]
    if y_value is not None:
        group_keys = [k for k in group_keys if k != "y"]
    if col_facet_value is not None:
        group_keys = [k for k in group_keys if k != "col_facet"]
    if not group_keys:
        group_keys = ["side"]
    for dx in grid:
        total_err = 0.0
        total_w = 0.0

        # グループ内で front vs back_reversed を比較
        for _, g in df0.groupby(group_keys, dropna=False):
            gf = g[g["direction"].astype(str) == DIR_FRONT]
            gb = g[g["direction"].astype(str) == DIR_BACK_REVERSED]
            if gf.empty or gb.empty:
                continue

            # 重複を平均化してから補間
            gf2 = gf.groupby(xcol, dropna=False)[feature].mean().reset_index()
            gb2 = gb.groupby(xcol, dropna=False)[feature].mean().reset_index()

            x1 = pd.to_numeric(gf2[xcol], errors="coerce").to_numpy(dtype=float)
            y1 = pd.to_numeric(gf2[feature], errors="coerce").to_numpy(dtype=float)
            x2 = pd.to_numeric(gb2[xcol], errors="coerce").to_numpy(dtype=float) + float(dx)
            y2 = pd.to_numeric(gb2[feature], errors="coerce").to_numpy(dtype=float)

            m1 = np.isfinite(x1) & np.isfinite(y1)
            m2 = np.isfinite(x2) & np.isfinite(y2)
            if m1.sum() < 3 or m2.sum() < 3:
                continue
            x1 = x1[m1]
            y1 = y1[m1]
            x2 = x2[m2]
            y2 = y2[m2]

            o1 = np.argsort(x1)
            o2 = np.argsort(x2)
            x1 = x1[o1]
            y1 = y1[o1]
            x2 = x2[o2]
            y2 = y2[o2]

            x2_min = float(np.nanmin(x2))
            x2_max = float(np.nanmax(x2))
            mask = (x1 >= x2_min) & (x1 <= x2_max)
            if mask.sum() < 3:
                continue

            # back_reversed を x1 上に線形補間
            y2i = np.interp(x1[mask], x2, y2)
            err = float(np.nanmean((y1[mask] - y2i) ** 2))
            if not np.isfinite(err):
                continue

            w = float(mask.sum())
            total_err += err * w
            total_w += w

        if total_w <= 0:
            continue
        score = total_err / total_w
        if score < best_err:
            best_err = score
            best_dx = float(dx)

    if not np.isfinite(best_dx):
        return 0.0
    return float(best_dx)


def apply_direction_x_offset(
    df_long: pd.DataFrame,
    *,
    feature: str,
    scope: str,
    max_mm: float,
    step_mm: float,
) -> tuple[pd.DataFrame, dict[tuple, float]]:
    """io ごとに x オフセットを推定して back_reversed 側へ適用する。"""
    df = df_long.copy()
    offsets: dict[tuple, float] = {}

    if scope not in X_OFFSET_SCOPE_CHOICES:
        raise ValueError(f"unknown x-offset-scope: {scope}")

    if scope == "io":
        for io in ["in", "out"]:
            dx = _estimate_x_offset_for_io(
                df,
                io=io,
                y_value=None,
                col_facet_value=None,
                feature=feature,
                max_mm=max_mm,
                step_mm=step_mm,
            )
            offsets[(io,)] = dx
            if abs(dx) <= 0:
                continue
            m = (df["io"].astype(str) == io) & (df["direction"].astype(str) == DIR_BACK_REVERSED)
            if m.any():
                df.loc[m, "x"] = pd.to_numeric(df.loc[m, "x"], errors="coerce") + float(dx)
    elif scope == "io_y":
        # (io, y) ごとに推定
        for io in ["in", "out"]:
            y_vals = pd.to_numeric(df.loc[df["io"].astype(str) == io, "y"], errors="coerce")
            y_levels = sorted(y_vals[np.isfinite(y_vals)].unique().tolist())
            for yv in y_levels:
                dx = _estimate_x_offset_for_io(
                    df,
                    io=io,
                    y_value=float(yv),
                    col_facet_value=None,
                    feature=feature,
                    max_mm=max_mm,
                    step_mm=step_mm,
                )
                offsets[(io, float(yv))] = dx
                if abs(dx) <= 0:
                    continue
                m = (
                    (df["io"].astype(str) == io)
                    & (pd.to_numeric(df["y"], errors="coerce") == float(yv))
                    & (df["direction"].astype(str) == DIR_BACK_REVERSED)
                )
                if m.any():
                    df.loc[m, "x"] = pd.to_numeric(df.loc[m, "x"], errors="coerce") + float(dx)
    elif scope == "io_facet":
        # (io, col_facet) ごとに推定
        for io in ["in", "out"]:
            cf_vals = df.loc[df["io"].astype(str) == io, "col_facet"].astype(str)
            cf_levels = sorted(cf_vals.dropna().unique().tolist())
            for cf in cf_levels:
                dx = _estimate_x_offset_for_io(
                    df,
                    io=io,
                    y_value=None,
                    col_facet_value=str(cf),
                    feature=feature,
                    max_mm=max_mm,
                    step_mm=step_mm,
                )
                offsets[(io, str(cf))] = dx
                if abs(dx) <= 0:
                    continue
                m = (
                    (df["io"].astype(str) == io)
                    & (df["col_facet"].astype(str) == str(cf))
                    & (df["direction"].astype(str) == DIR_BACK_REVERSED)
                )
                if m.any():
                    df.loc[m, "x"] = pd.to_numeric(df.loc[m, "x"], errors="coerce") + float(dx)
    else:
        # (io, y, col_facet) ごとに推定
        for io in ["in", "out"]:
            base = df[df["io"].astype(str) == io].copy()
            if base.empty:
                continue
            y_vals = pd.to_numeric(base["y"], errors="coerce")
            y_levels = sorted(y_vals[np.isfinite(y_vals)].unique().tolist())
            cf_levels = sorted(base["col_facet"].astype(str).dropna().unique().tolist())
            for cf in cf_levels:
                for yv in y_levels:
                    dx = _estimate_x_offset_for_io(
                        df,
                        io=io,
                        y_value=float(yv),
                        col_facet_value=str(cf),
                        feature=feature,
                        max_mm=max_mm,
                        step_mm=step_mm,
                    )
                    offsets[(io, float(yv), str(cf))] = dx
                    if abs(dx) <= 0:
                        continue
                    m = (
                        (df["io"].astype(str) == io)
                        & (pd.to_numeric(df["y"], errors="coerce") == float(yv))
                        & (df["col_facet"].astype(str) == str(cf))
                        & (df["direction"].astype(str) == DIR_BACK_REVERSED)
                    )
                    if m.any():
                        df.loc[m, "x"] = pd.to_numeric(df.loc[m, "x"], errors="coerce") + float(dx)

    # x_abs は x から再計算（diffモードで使う）
    df["x_abs"] = pd.to_numeric(df["x"], errors="coerce").abs()
    return df, offsets


def _mean_line_from_two_directions(
    sub: pd.DataFrame,
    *,
    xcol: str,
    feature: str,
    side: str,
) -> tuple[np.ndarray | None, np.ndarray | None]:
    """direction=front/back_reversed の2系列から平均線 (xu, ym) を作る。

    sub は少なくとも [direction, side, xcol, feature] を含み、(direction, side, xcol) ごとに平均済みを想定。
    """
    sf = sub[(sub["direction"].astype(str) == DIR_FRONT) & (sub["side"] == side)]
    sb = sub[(sub["direction"].astype(str) == DIR_BACK_REVERSED) & (sub["side"] == side)]
    if sf.empty or sb.empty:
        return None, None

    sf = sf.groupby(xcol, dropna=False)[feature].mean().reset_index()
    sb = sb.groupby(xcol, dropna=False)[feature].mean().reset_index()

    x1 = pd.to_numeric(sf[xcol], errors="coerce").to_numpy(dtype=float)
    y1 = pd.to_numeric(sf[feature], errors="coerce").to_numpy(dtype=float)
    x2 = pd.to_numeric(sb[xcol], errors="coerce").to_numpy(dtype=float)
    y2 = pd.to_numeric(sb[feature], errors="coerce").to_numpy(dtype=float)

    m1 = np.isfinite(x1) & np.isfinite(y1)
    m2 = np.isfinite(x2) & np.isfinite(y2)
    # 疎なデータでも平均線を作れるように、最低2点から許容
    if m1.sum() < 2 or m2.sum() < 2:
        return None, None

    x1 = x1[m1]
    y1 = y1[m1]
    x2 = x2[m2]
    y2 = y2[m2]

    o1 = np.argsort(x1)
    o2 = np.argsort(x2)
    x1 = x1[o1]
    y1 = y1[o1]
    x2 = x2[o2]
    y2 = y2[o2]

    lo = max(float(np.min(x1)), float(np.min(x2)))
    hi = min(float(np.max(x1)), float(np.max(x2)))
    if not np.isfinite(lo) or not np.isfinite(hi) or hi <= lo:
        return None, None

    xu = np.unique(np.concatenate([x1, x2]))
    xu = xu[(xu >= lo) & (xu <= hi)]
    if xu.size < 2:
        return None, None

    y1i = np.interp(xu, x1, y1)
    y2i = np.interp(xu, x2, y2)
    ym = 0.5 * (y1i + y2i)
    return xu, ym


