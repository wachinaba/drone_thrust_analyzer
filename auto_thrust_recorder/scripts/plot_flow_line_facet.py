def _safe_to_numeric(df: pd.DataFrame, cols: Iterable[str]) -> pd.DataFrame:
    for c in cols:
        if c in df.columns:
            df[c] = pd.to_numeric(df[c], errors="coerce")
    return df


def load_and_filter(input_path: Path, target_thrust: float | None) -> pd.DataFrame:
    """結合CSVを読み込み、target_thrust でフィルタし、keyword 平均を行った DataFrame を返す。"""
    try:
        df = pd.read_csv(input_path)
    except Exception as e:
        raise RuntimeError(f"CSV 読み込みに失敗しました: {e}")

    required_cols = [
        "flow_distance",
        "flow_height",
        "flow_direction",
        "front_in",
        "front_out",
        "rear_in",
        "rear_out",
        "target_thrust",
        "direction",
    ]
    missing = [c for c in required_cols if c not in df.columns]
    if missing:
        raise ValueError(f"必須列が不足しています: {', '.join(missing)}")

    num_cols = [
        "flow_distance",
        "flow_height",
        "flow_direction",
        "front_in",
        "front_out",
        "rear_in",
        "rear_out",
        "target_thrust",
        "distance",
        "fold_angle",
        "slant_angle",
        "height",
        "prop_spacing",
        "tilt_angle",
        "wall_spacing",
    ]
    df = _safe_to_numeric(df, num_cols)

    if df["target_thrust"].notna().sum() == 0:
        raise ValueError("target_thrust 列に有効な値がありません。")
    if target_thrust is None:
        th = df["target_thrust"].max()
        df = df[df["target_thrust"] == th].copy()
        print(f"target_thrust 未指定のため、最大値 {th} のみを使用します。")
    else:
        df = df[df["target_thrust"] == target_thrust].copy()
        if df.empty:
            raise ValueError(f"指定された target_thrust={target_thrust} に一致する行がありません。")

    # keyword の平均化：keyword 以外のパラメータでグループ化し、数値列は平均
    keyword_col = "keyword"
    if keyword_col in df.columns:
        numeric_cols = df.select_dtypes(include=[np.number]).columns.tolist()
        group_cols = [c for c in df.columns if c not in numeric_cols and c != keyword_col]
        if not group_cols:
            group_cols = [c for c in df.columns if c != keyword_col]
        df = (
            df.groupby(group_cols, dropna=False)
            .mean(numeric_only=True)
            .reset_index()
        )
        print("keyword 列を除いて数値列を平均化しました。")

    return df


def reconstruct_components(df: pd.DataFrame, single_angle_mode: str = "nan") -> pd.DataFrame:
    """flow_direction[deg] と各センサ値から |u_x|,|u_y|,|u| を再構成する（plot_flow_2d_facet.py と同等）。"""
    sensors = ["front_in", "front_out", "rear_in", "rear_out"]
    dfc = df.copy()

    base_index_cols_all = [
        "direction",  # 色分け用に保持（fitもこの単位で行う）
        "distance",
        "flow_distance",
        "flow_height",
        "fold_angle",
        "slant_angle",
        "height",
        "prop_spacing",
        "tilt_angle",
        "wall_spacing",
        "target_thrust",
    ]
    base_index_cols = [c for c in base_index_cols_all if c in dfc.columns]
    if "flow_distance" not in base_index_cols or "flow_height" not in base_index_cols:
        raise ValueError("flow_distance および flow_height 列が必要です。")

    # phi 探索グリッド（0〜pi、1deg刻み相当）
    phi_grid = np.linspace(0.0, np.pi, 180, endpoint=False)

    all_pivot = None

    for sensor in sensors:
        if sensor not in dfc.columns:
            continue

        cols = base_index_cols + ["flow_direction", sensor]
        tmp = dfc[cols].dropna(subset=["flow_direction", sensor]).copy()
        if tmp.empty:
            continue

        rows = []
        for keys, g in tmp.groupby(base_index_cols):
            m_raw = g[sensor].to_numpy(dtype=float)
            theta_raw_deg = g["flow_direction"].to_numpy(dtype=float)

            # センサごとに角度基準を補正（front を基準に、rear は反転）
            if sensor.startswith("rear"):
                theta_raw_deg = 180.0 - theta_raw_deg

            theta_raw = np.deg2rad(theta_raw_deg)
            if len(m_raw) < 1:
                continue

            valid_mask = np.isfinite(m_raw) & (np.abs(m_raw) > ZERO_EPS) & np.isfinite(theta_raw)
            if not np.any(valid_mask):
                continue
            m = m_raw[valid_mask]
            theta = theta_raw[valid_mask]

            unique_theta = np.unique(theta)
            if unique_theta.size >= 2:
                angle_span_rad = float(unique_theta.max() - unique_theta.min())
                angle_span_deg = np.degrees(angle_span_rad)
                if angle_span_deg < ANGLE_SPAN_MIN_DEG:
                    continue
            if unique_theta.size == 1:
                if single_angle_mode == "nan":
                    continue
                phi_best = float(unique_theta[0])
                U_best = float(np.nanmean(m))
                if not np.isfinite(U_best) or U_best < 0:
                    continue
            else:
                cos_diff = np.abs(np.cos(theta[:, None] - phi_grid[None, :]))
                denom = np.sum(cos_diff**2, axis=0)
                valid = denom > 1e-8
                if not np.any(valid):
                    continue

                num = np.sum(cos_diff * m[:, None], axis=0)
                U = np.zeros_like(phi_grid)
                U[valid] = num[valid] / denom[valid]

                pred = U[None, :] * cos_diff
                err = np.sum((pred - m[:, None]) ** 2, axis=0)
                err[~valid] = np.inf

                idx = int(np.argmin(err))
                phi_best = float(phi_grid[idx])
                U_best = float(U[idx])
                if not np.isfinite(U_best) or U_best < 0:
                    continue

            ux_abs = U_best * abs(np.cos(phi_best))
            uy_abs = U_best * abs(np.sin(phi_best))

            row = {col: val for col, val in zip(base_index_cols, keys)}
            row[f"{sensor}_ux_abs"] = float(ux_abs)
            row[f"{sensor}_uy_abs"] = float(uy_abs)
            row[f"{sensor}_mag"] = float(U_best)
            row[f"{sensor}_n_samples"] = int(m.size)
            row[f"{sensor}_n_unique_angles"] = int(unique_theta.size)
            row[f"{sensor}_phi_deg"] = float(np.degrees(phi_best))
            rows.append(row)

        if not rows:
            continue

        pivot = pd.DataFrame(rows).set_index(base_index_cols)
        all_pivot = pivot if all_pivot is None else all_pivot.join(pivot, how="outer")

    if all_pivot is None or all_pivot.empty:
        raise ValueError("有効な flow_direction とセンサ値の組から再構成できるデータがありません。")

    return all_pivot.reset_index()


def build_long_with_coordinates(components_df: pd.DataFrame, *, y_in_origin: float) -> pd.DataFrame:
    """再構成結果を (x,y) 付きロング形式に変換する。"""
    sensors = ["front_in", "front_out", "rear_in", "rear_out"]
    meas_prefixes = tuple(f"{s}_" for s in sensors)
    idx_cols = [c for c in components_df.columns if not c.startswith(meas_prefixes)]

    long_parts = []
    for sensor in sensors:
        ux_col = f"{sensor}_ux_abs"
        uy_col = f"{sensor}_uy_abs"
        mag_col = f"{sensor}_mag"
        meta_ns_col = f"{sensor}_n_samples"
        meta_na_col = f"{sensor}_n_unique_angles"
        meta_phi_col = f"{sensor}_phi_deg"

        use_cols = [c for c in [ux_col, uy_col, mag_col, meta_ns_col, meta_na_col, meta_phi_col] if c in components_df.columns]
        if not use_cols or mag_col not in use_cols:
            continue

        sub = components_df[idx_cols + use_cols].copy()
        sub = sub.dropna(subset=[mag_col])
        if sub.empty:
            continue

        sub = sub.rename(
            columns={
                ux_col: "ux_abs",
                uy_col: "uy_abs",
                mag_col: "u_mag",
                meta_ns_col: "n_samples",
                meta_na_col: "n_unique_angles",
                meta_phi_col: "phi_deg",
            }
        )
        sub["sensor"] = sensor
        long_parts.append(sub)

    if not long_parts:
        raise ValueError("有効な |u| データがありません。")

    df_long = pd.concat(long_parts, ignore_index=True)

    # 座標付与
    if "flow_distance" not in df_long.columns or "flow_height" not in df_long.columns:
        raise ValueError("flow_distance, flow_height 列が必要です。")

    df_long["flow_distance_mm"] = pd.to_numeric(df_long["flow_distance"], errors="coerce") * 1000.0

    df_long["side"] = np.where(df_long["sensor"].astype(str).str.startswith("front"), "front", "rear")
    df_long["io"] = np.where(df_long["sensor"].astype(str).str.endswith("in"), "in", "out")

    # x 座標: front=+flow_distance, rear=-flow_distance
    # 座標系を反転: front=-flow_distance, rear=+flow_distance
    df_long["x"] = np.where(df_long["side"] == "front", -df_long["flow_distance_mm"], df_long["flow_distance_mm"])
    df_long["x_abs"] = df_long["x"].abs()

    # y 座標: in=y_in_origin-flow_height, out=-flow_height
    fh = pd.to_numeric(df_long["flow_height"], errors="coerce")
    df_long["y"] = np.where(df_long["io"] == "in", float(y_in_origin) - fh, -fh)

    return df_long


def add_col_facet_label(df_long: pd.DataFrame, col_keys: list[str]) -> pd.DataFrame:
    col_keys = [k for k in (col_keys or []) if k in df_long.columns]
    if not col_keys:
        df_long["col_facet"] = "all"
        return df_long

    def _format_val(v):
        if pd.isna(v):
            return "nan"
        try:
            fv = float(v)
            if np.isfinite(fv) and abs(fv - round(fv)) < 1e-6:
                return f"{int(round(fv))}"
            return f"{fv:g}" if np.isfinite(fv) else str(v)
        except Exception:
            return str(v)

    def _col_label(r):
        parts = []
        for k in col_keys:
            parts.append(f"{k}={_format_val(r[k])}")
        return ", ".join(parts)

    df_long = df_long.copy()
    df_long["col_facet"] = df_long.apply(_col_label, axis=1)
    return df_long


def _robust_max_iqr(vals: pd.Series) -> float:
    vals = pd.to_numeric(vals, errors="coerce")
    vals = vals[np.isfinite(vals) & (vals > ZERO_EPS)]
    if vals.empty:
        return np.nan
    q1 = vals.quantile(0.25)
    q3 = vals.quantile(0.75)
    iqr = q3 - q1
    if np.isfinite(iqr) and iqr > 0:
        thresh = q3 + ROBUST_IQR_K * iqr
        vals = vals[vals <= thresh]
        if vals.empty:
            return np.nan
    return float(vals.max()) if not vals.empty else np.nan


def _compute_ylim(vals: pd.Series) -> tuple[float, float] | None:
    v = pd.to_numeric(vals, errors="coerce")
    v = v[np.isfinite(v)]
    if v.empty:
        return None
    lo = float(v.min())
    hi = float(v.max())
    if not np.isfinite(lo) or not np.isfinite(hi):
        return None
    if hi == lo:
        pad = 1.0 if lo == 0 else 0.05 * abs(lo)
        return lo - pad, hi + pad
    pad = 0.05 * (hi - lo)
    return lo - pad, hi + pad


def _compute_io_y_lims(
    df_long: pd.DataFrame,
    *,
    feature: str,
    mode: str,
) -> dict[str, tuple[float, float]]:
    """io ごとに縦軸スケールを全y・全facetで固定するための ylim を計算する。"""
    out: dict[str, tuple[float, float]] = {}
    if df_long.empty or feature not in df_long.columns:
        return out

    if mode == "diff":
        # diff: 全体で front-rear を作ってその範囲で決める（io別）
        if "x_abs" not in df_long.columns:
            return out
        for io in ["in", "out"]:
            base = df_long[df_long["io"].astype(str) == io].copy()
            if base.empty:
                continue
            sub = (
                base.groupby(["col_facet", "y", "direction", "side", "x_abs"], dropna=False)[feature]
                .mean()
                .reset_index()
            )
            piv = (
                sub.pivot_table(
                    index=["col_facet", "y", "direction", "x_abs"],
                    columns="side",
                    values=feature,
                    aggfunc="mean",
                )
                .reset_index()
            )
            if ("front" not in piv.columns) or ("rear" not in piv.columns):
                continue
            piv = piv.dropna(subset=["front", "rear"]).copy()
            if piv.empty:
                continue
            diff_vals = pd.to_numeric(piv["front"], errors="coerce") - pd.to_numeric(piv["rear"], errors="coerce")
            lim = _compute_ylim(diff_vals)
            if lim is not None:
                out[io] = lim
        return out

    # normal: io別に単純に feature のmin/max（全facet・全y）
    for io in ["in", "out"]:
        vals = df_long.loc[df_long["io"].astype(str) == io, feature]
        lim = _compute_ylim(vals)
        if lim is not None:
            out[io] = lim
    return out


def _scope_key_from_row(r: pd.Series, scope: str) -> str:
    """x-offset-scope と同じ単位でキー文字列を作る（K推定/適用にも使う）。"""
    if scope == "io":
        return f"io={r.get('io')}"
    if scope == "io_y":
        return f"io={r.get('io')}|y={r.get('y')}"
    if scope == "io_facet":
        return f"io={r.get('io')}|col_facet={r.get('col_facet')}"
    if scope == "io_y_facet":
        return f"io={r.get('io')}|y={r.get('y')}|col_facet={r.get('col_facet')}"
    raise ValueError(f"unknown scope: {scope}")


def _add_scope_key_column(df: pd.DataFrame, scope: str) -> pd.DataFrame:
    df = df.copy()
    df["scope_key"] = df.apply(lambda r: _scope_key_from_row(r, scope), axis=1)
    return df


