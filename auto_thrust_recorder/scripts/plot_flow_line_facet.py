def _resample_line_uniform(x: np.ndarray, y: np.ndarray, *, step: float) -> tuple[np.ndarray, np.ndarray]:
    """(x,y) を x 方向に一定間隔でリサンプルする（線形補間）。"""
    if step <= 0 or (not np.isfinite(step)):
        raise ValueError("dot-step-mm は正の値が必要です。")
    m = np.isfinite(x) & np.isfinite(y)
    if m.sum() < 2:
        return np.array([]), np.array([])
    x = x[m]
    y = y[m]
    o = np.argsort(x)
    x = x[o]
    y = y[o]
    lo = float(np.min(x))
    hi = float(np.max(x))
    if not np.isfinite(lo) or not np.isfinite(hi) or hi <= lo:
        return np.array([]), np.array([])
    # 端点を含めてサンプル（hi を超えないように）
    xs = np.arange(lo, hi + 1e-9, step, dtype=float)
    # scatter 用なので1点でもOK（レンジが狭いケースを救う）
    if xs.size < 1:
        return np.array([]), np.array([])
    ys = np.interp(xs, x, y)
    return xs, ys


def compute_mean_dots_points(
    df_long: pd.DataFrame,
    *,
    col_levels: list[str],
    y_levels: list[float],
    feature: str,
    mode: str,
    dot_step_mm: float,
) -> tuple[pd.DataFrame, dict[tuple[str, float, str], dict[str, int]]]:
    """mean_dots 用の点列を生成する（x-y配置、色は feature）。

    返り値:
      - dots: cols=[col_facet, y_plot, io, side, x_plot, val]
      - debug_counts: 欠損/不成立の状況（rows空のときの調査用）
    """
    if df_long.empty or feature not in df_long.columns:
        return pd.DataFrame(), {}

    xcol = "x_abs" if mode == "diff" else "x"

    rows: list[dict] = []
    debug_counts: dict[tuple[str, float, str], dict[str, int]] = {}

    def _dbg_inc(col_facet: str, yv: float, io: str, reason: str) -> None:
        k = (str(col_facet), float(yv), str(io))
        if k not in debug_counts:
            debug_counts[k] = {}
        debug_counts[k][reason] = debug_counts[k].get(reason, 0) + 1

    for clab in col_levels:
        for yv in y_levels:
            base = df_long[(df_long["col_facet"] == clab) & (df_long["y"] == yv)]
            if base.empty:
                continue

            for io in ["in", "out"]:
                g0 = base[base["io"].astype(str) == io]
                if g0.empty:
                    continue

                dirs_here = set(g0["direction"].dropna().astype(str).unique().tolist())
                if (DIR_FRONT not in dirs_here) or (DIR_BACK_REVERSED not in dirs_here):
                    _dbg_inc(clab, yv, io, "missing_direction(front/back_reversed)")
                    continue

                g = (
                    g0.groupby(["direction", "side", xcol], dropna=False)[feature]
                    .mean()
                    .reset_index()
                )
                sides_here = set(g["side"].dropna().astype(str).unique().tolist())
                if mode == "diff":
                    if ("front" not in sides_here) or ("rear" not in sides_here):
                        _dbg_inc(clab, yv, io, "missing_side(front/rear)")
                        continue

                if mode == "diff":
                    # diff の mean_dots は (frontのdirection平均線) - (rearのdirection平均線)
                    xu_f, yf, reason_f = _mean_line_diag_two_dirs(g, xcol=xcol, feature=feature, side="front")
                    if xu_f is None or yf is None:
                        _dbg_inc(clab, yv, io, f"mean_line_fail:front:{reason_f}")
                        continue
                    xu_r, yr, reason_r = _mean_line_diag_two_dirs(g, xcol=xcol, feature=feature, side="rear")
                    if xu_r is None or yr is None:
                        _dbg_inc(clab, yv, io, f"mean_line_fail:rear:{reason_r}")
                        continue

                    lo = max(float(np.min(xu_f)), float(np.min(xu_r)))
                    hi = min(float(np.max(xu_f)), float(np.max(xu_r)))
                    if not np.isfinite(lo) or not np.isfinite(hi) or hi <= lo:
                        _dbg_inc(clab, yv, io, "diff_mean_no_overlap(front/rear)")
                        continue
                    xu = np.unique(np.concatenate([xu_f, xu_r]))
                    xu = xu[(xu >= lo) & (xu <= hi)]
                    if xu.size < 2:
                        _dbg_inc(clab, yv, io, "diff_mean_too_few_overlap_points")
                        continue
                    yf_i = np.interp(xu, xu_f, yf)
                    yr_i = np.interp(xu, xu_r, yr)
                    ydiff = yf_i - yr_i

                    xs, ys = _resample_line_uniform(xu, ydiff, step=float(dot_step_mm))
                    if xs.size == 0:
                        _dbg_inc(clab, yv, io, "resample_empty:diff_mean")
                        continue
                    for xx, yy in zip(xs, ys):
                        rows.append(
                            {
                                "col_facet": clab,
                                "y_plot": float(yv),
                                "io": io,
                                "side": "diff",
                                "x_plot": float(xx),
                                "val": float(yy),
                            }
                        )
                else:
                    for side in ["front", "rear"]:
                        if side not in sides_here:
                            _dbg_inc(clab, yv, io, f"missing_side:{side}")
                            continue
                        xu, ym, reason = _mean_line_diag_two_dirs(g, xcol=xcol, feature=feature, side=side)
                        if xu is None or ym is None:
                            _dbg_inc(clab, yv, io, f"mean_line_fail:{side}:{reason}")
                            continue
                        xs, ys = _resample_line_uniform(xu, ym, step=float(dot_step_mm))
                        if xs.size == 0:
                            _dbg_inc(clab, yv, io, f"resample_empty:{side}")
                            continue
                        for xx, yy in zip(xs, ys):
                            rows.append(
                                {
                                    "col_facet": clab,
                                    "y_plot": float(yv),
                                    "io": io,
                                    "side": side,
                                    "x_plot": float(xx),
                                    "val": float(yy),
                                }
                            )

    return pd.DataFrame(rows), debug_counts


